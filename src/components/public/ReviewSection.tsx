'use client';

import React, { useState } from 'react';
import { useLanguageStore } from '@/store/useLanguageStore';
import { t } from '@/lib/i18n';
import { Star, CheckCircle, Sparkles, MessageSquare, ThumbsUp, User } from 'lucide-react';

interface ReviewItem {
  id: string;
  authorName: string;
  rating: number;
  title: string;
  comment: string;
  isVerifiedPurchase: boolean;
  isAutoGenerated?: boolean;
  createdAt?: string | Date;
}

interface ReviewSectionProps {
  productId: string;
  productName: string;
  initialReviews: ReviewItem[];
}

export const ReviewSection: React.FC<ReviewSectionProps> = ({
  productId,
  productName,
  initialReviews,
}) => {
  const [reviews, setReviews] = useState<ReviewItem[]>(initialReviews);
  const [isGenerating, setIsGenerating] = useState(false);
  const [showForm, setShowForm] = useState(false);
  const { currentLocale } = useLanguageStore();

  // Form State
  const [authorName, setAuthorName] = useState('');
  const [rating, setRating] = useState(5);
  const [title, setTitle] = useState('');
  const [comment, setComment] = useState('');
  const [isSubmitting, setIsSubmitting] = useState(false);

  const averageRating =
    reviews.length > 0
      ? (reviews.reduce((acc, r) => acc + r.rating, 0) / reviews.length).toFixed(1)
      : '5.0';

  const handleGenerateAI = async () => {
    setIsGenerating(true);
    try {
      const res = await fetch('/api/avis/generate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          productId,
          productName,
          count: 3,
          language: currentLocale.toUpperCase(),
        }),
      });
      const data = await res.json();
      if (data.reviews) {
        setReviews((prev) => [...data.reviews, ...prev]);
      }
    } catch (e) {
      console.error('Erreur génération avis IA', e);
    } finally {
      setIsGenerating(false);
    }
  };

  const handleSubmitReview = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!authorName.trim() || !comment.trim()) return;

    setIsSubmitting(true);
    const newRev: ReviewItem = {
      id: `rev-${Date.now()}`,
      authorName,
      rating,
      title: title || 'Très bon produit',
      comment,
      isVerifiedPurchase: false,
      isAutoGenerated: false,
    };

    setReviews((prev) => [newRev, ...prev]);
    setAuthorName('');
    setTitle('');
    setComment('');
    setShowForm(false);
    setIsSubmitting(false);
  };

  return (
    <div className="mt-12 bg-white dark:bg-slate-900 rounded-3xl p-6 sm:p-8 border border-slate-100 dark:border-slate-800 shadow-sm">
      <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4 pb-6 border-b border-slate-100 dark:border-slate-800">
        <div>
          <div className="flex items-center gap-3">
            <h3 className="text-xl font-black text-slate-900 dark:text-slate-100">
              {t(currentLocale, 'reviews.title')}
            </h3>
            <span className="bg-blue-100 text-blue-800 dark:bg-blue-950 dark:text-blue-300 text-xs font-black px-2.5 py-0.5 rounded-full">
              {reviews.length}
            </span>
          </div>
          <div className="flex items-center gap-2 mt-1">
            <div className="flex text-amber-400">
              {[...Array(5)].map((_, i) => (
                <Star
                  key={i}
                  className={`w-4 h-4 ${
                    i < Math.round(Number(averageRating))
                      ? 'fill-current text-amber-400'
                      : 'text-slate-200 dark:text-slate-700'
                  }`}
                />
              ))}
            </div>
            <span className="text-sm font-bold text-slate-700 dark:text-slate-300">
              {averageRating} / 5
            </span>
          </div>
        </div>

        <div className="flex flex-wrap items-center gap-2">
          {/* Bouton IA Générateur Démo / Admin */}
          <button
            onClick={handleGenerateAI}
            disabled={isGenerating}
            className="flex items-center gap-1.5 px-3 py-2 bg-gradient-to-r from-blue-700 to-indigo-800 hover:from-blue-800 hover:to-indigo-900 text-white rounded-xl text-xs font-bold shadow-md shadow-blue-500/20 disabled:opacity-50 transition-all"
            title="Générer automatiquement des avis béninois réalistes"
          >
            <Sparkles className="w-3.5 h-3.5 text-amber-300 animate-pulse" />
            <span>{isGenerating ? 'Génération...' : '✨ Avis Béninois IA'}</span>
          </button>

          <button
            onClick={() => setShowForm(!showForm)}
            className="px-4 py-2 bg-blue-50 hover:bg-blue-100 text-blue-700 dark:bg-slate-800 dark:text-blue-300 rounded-xl text-xs font-bold transition-colors"
          >
            {showForm ? t(currentLocale, 'common.cancel') : t(currentLocale, 'reviews.writeReview')}
          </button>
        </div>
      </div>

      {/* Formulaire d'avis client */}
      {showForm && (
        <form onSubmit={handleSubmitReview} className="my-6 p-5 bg-blue-50/50 dark:bg-slate-800/40 rounded-2xl border border-blue-100 dark:border-slate-700 space-y-4">
          <h4 className="text-sm font-bold text-slate-800 dark:text-slate-200">
            {t(currentLocale, 'reviews.writeReview')}
          </h4>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            <div>
              <label className="block text-xs font-semibold text-slate-700 dark:text-slate-300 mb-1">
                {t(currentLocale, 'reviews.yourName')} *
              </label>
              <input
                type="text"
                required
                value={authorName}
                onChange={(e) => setAuthorName(e.target.value)}
                placeholder="Ex: Dossou Koffi"
                className="w-full px-3 py-2 rounded-xl text-xs border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 focus:outline-none focus:ring-2 focus:ring-blue-600"
              />
            </div>

            <div>
              <label className="block text-xs font-semibold text-slate-700 dark:text-slate-300 mb-1">
                {t(currentLocale, 'reviews.yourRating')} *
              </label>
              <div className="flex gap-2 items-center h-9">
                {[1, 2, 3, 4, 5].map((star) => (
                  <button
                    key={star}
                    type="button"
                    onClick={() => setRating(star)}
                    className="p-1 text-slate-300 hover:text-amber-400 focus:outline-none"
                  >
                    <Star
                      className={`w-5 h-5 ${star <= rating ? 'fill-amber-400 text-amber-400' : ''}`}
                    />
                  </button>
                ))}
              </div>
            </div>
          </div>

          <div>
            <label className="block text-xs font-semibold text-slate-700 dark:text-slate-300 mb-1">
              {t(currentLocale, 'reviews.reviewTitle')}
            </label>
            <input
              type="text"
              value={title}
              onChange={(e) => setTitle(e.target.value)}
              placeholder="Ex: Très satisfait de la commande"
              className="w-full px-3 py-2 rounded-xl text-xs border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 focus:outline-none focus:ring-2 focus:ring-blue-600"
            />
          </div>

          <div>
            <label className="block text-xs font-semibold text-slate-700 dark:text-slate-300 mb-1">
              {t(currentLocale, 'reviews.reviewComment')} *
            </label>
            <textarea
              required
              rows={3}
              value={comment}
              onChange={(e) => setComment(e.target.value)}
              placeholder="Partagez votre avis sur la livraison et le produit..."
              className="w-full px-3 py-2 rounded-xl text-xs border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 focus:outline-none focus:ring-2 focus:ring-blue-600"
            />
          </div>

          <div className="flex justify-end gap-2">
            <button
              type="button"
              onClick={() => setShowForm(false)}
              className="px-4 py-2 text-xs font-semibold text-slate-600 hover:bg-slate-200 rounded-xl"
            >
              {t(currentLocale, 'common.cancel')}
            </button>
            <button
              type="submit"
              disabled={isSubmitting}
              className="px-5 py-2 text-xs font-bold text-white bg-blue-600 hover:bg-blue-700 rounded-xl shadow"
            >
              {t(currentLocale, 'reviews.submitReview')}
            </button>
          </div>
        </form>
      )}

      {/* Liste des avis */}
      <div className="divide-y divide-slate-100 dark:divide-slate-800">
        {reviews.map((rev) => (
          <div key={rev.id} className="py-5 space-y-2">
            <div className="flex items-center justify-between">
              <div className="flex items-center gap-2">
                <div className="w-8 h-8 rounded-full bg-blue-100 dark:bg-slate-800 flex items-center justify-center text-blue-700 dark:text-blue-300 font-bold text-xs">
                  {rev.authorName.charAt(0)}
                </div>
                <div>
                  <h5 className="font-bold text-xs text-slate-900 dark:text-slate-100">
                    {rev.authorName}
                  </h5>
                  <div className="flex items-center gap-1.5 mt-0.5">
                    <div className="flex text-amber-400">
                      {[...Array(5)].map((_, i) => (
                        <Star
                          key={i}
                          className={`w-3 h-3 ${
                            i < rev.rating ? 'fill-current text-amber-400' : 'text-slate-200'
                          }`}
                        />
                      ))}
                    </div>
                    {rev.isVerifiedPurchase && (
                      <span className="flex items-center gap-1 text-[10px] text-emerald-600 dark:text-emerald-400 font-semibold">
                        <CheckCircle className="w-3 h-3" />
                        <span>{t(currentLocale, 'product.verifiedPurchase')}</span>
                      </span>
                    )}
                  </div>
                </div>
              </div>

              {rev.isAutoGenerated && (
                <span className="text-[10px] bg-slate-100 text-slate-500 dark:bg-slate-800 dark:text-slate-400 px-2 py-0.5 rounded-full">
                  Vérifié MAHUGNON
                </span>
              )}
            </div>

            {rev.title && (
              <h6 className="font-semibold text-xs text-slate-800 dark:text-slate-200">
                {rev.title}
              </h6>
            )}

            <p className="text-xs text-slate-600 dark:text-slate-300 leading-relaxed">
              {rev.comment}
            </p>
          </div>
        ))}
      </div>
    </div>
  );
};
