export interface GenerateReviewsOptions {
  productName: string;
  productDescription?: string;
  count: number;
  targetRating?: number; // e.g. 5 or mixed
  tone?: 'enthusiastic' | 'balanced' | 'local';
  language?: 'FR' | 'EN' | 'FON' | 'MIX';
}

export interface GeneratedReview {
  authorName: string;
  rating: number;
  title: string;
  comment: string;
  isVerifiedPurchase: boolean;
  isAutoGenerated: boolean;
}

const BENIN_NAMES = [
  'Adjovi Dossou',
  'Koffi Bio',
  'Akossiwa Fadil',
  'Sènan Rachidath',
  'Chabi Yaovi',
  'Ayélé Nadège',
  'Kossi Hounkpatin',
  'Afi Houndété',
  'Dossou Mensah',
  'Rachidath Gbaguidi',
  'Yaovi Agbodjan',
  'Bio Séro',
  'Nadège Assogba',
  'Fadil Alabi',
  'Sèna Zannou',
];

const LOCAL_CITIES = ['Cotonou (Akpakpa)', 'Cotonou (Fidjrossè)', 'Cotonou (Cadjehoun)', 'Porto-Novo', 'Abomey-Calavi', 'Parakou'];

/**
 * Générateur local de secours ultraréaliste pour le Bénin en cas d'absence de clé API OpenAI/Groq
 */
function generateFallbackReviews(options: GenerateReviewsOptions): GeneratedReview[] {
  const reviews: GeneratedReview[] = [];
  const titlesFR = [
    'Très bonne qualité, livré dans la journée',
    'Conforme à ce que j\'ai commandé',
    'Super produit, je recommande vivement',
    'Livraison rapide à Cotonou par zémidjan',
    'Très satisfait, bonne communication',
    'Excellent rapport qualité-prix',
    'Le vendeur m\'a rappelé dans les 15 minutes',
    'Paiement MoMo effectué à la livraison sans souci',
  ];

  const commentsFR = [
    (p: string, c: string) => `J'ai commandé ${p} depuis ${c}. On m'a appelé rapidement pour confirmer mon quartier et le livreur est arrivé à l'heure. Produit propre et authentique.`,
    (p: string, c: string) => `Très belle finition pour ${p}. J'avais un doute sur la qualité mais en ouvrant le colis à la livraison, c'était impeccable. Merci MAHUGNON !`,
    (p: string, c: string) => `Bonne expérience à ${c}. Le produit (${p}) correspond tout à fait à la photo. Petit bémol sur le temps de trouver ma ruelle mais le livreur a été très poli.`,
    (p: string, c: string) => `Service sérieux et rassurant. Pas besoin de payer d'avance par carte, j'ai vérifié mon article puis payé par MTN MoMo sur place.`,
    (p: string, c: string) => `Je l'ai acheté pour un cadeau de famille. Qualité irréprochable et emballage soigné. Je repasserai commande sans hésiter.`,
  ];

  const titlesFON = [
    'Nǔ ɖagbe wɛ, é jɛ jí tawun',
    'Azɔ̌ ɖagbe sín Kutɔnu',
    'Un mɔ nǔ e un ba é pɛ́pɛ́',
  ];

  const commentsFON = [
    (p: string) => `Nǔ elɔ (${p}) víví nú mì tawun. Ye ylɔ́ mì tlolo ɖò alokan jí bo hɛn wá nú mì ɖò xá ce mɛ. Awǎ nú mitɔn !`,
    (p: string) => `Akwɛ tɔn kpo nǔɖagbe tɔn kpo sɔgbe. Un sú akwɛ hwenu e zɔnlinxɔ́tɔ́ ɔ wá é. É nyɔ́ ɖesu.`,
  ];

  for (let i = 0; i < options.count; i++) {
    const name = BENIN_NAMES[i % BENIN_NAMES.length];
    const city = LOCAL_CITIES[i % LOCAL_CITIES.length];
    const isFon = options.language === 'FON' || (options.language === 'MIX' && i % 3 === 2);

    let title: string;
    let comment: string;
    let rating = 5;

    // Détermination de la note (quelques notes de 4 pour le réalisme)
    if (options.targetRating) {
      rating = options.targetRating;
    } else {
      rating = i % 5 === 0 ? 4 : 5;
    }

    if (isFon) {
      title = titlesFON[i % titlesFON.length];
      comment = commentsFON[i % commentsFON.length](options.productName);
    } else {
      title = titlesFR[i % titlesFR.length];
      comment = commentsFR[i % commentsFR.length](options.productName, city);
    }

    reviews.push({
      authorName: name,
      rating,
      title,
      comment,
      isVerifiedPurchase: true,
      isAutoGenerated: true,
    });
  }

  return reviews;
}

/**
 * Génère des avis clients réalistes via OpenAI GPT-4o-mini ou Groq Llama 3.1
 */
export async function generateAIReviews(options: GenerateReviewsOptions): Promise<GeneratedReview[]> {
  const openAiKey = process.env.OPENAI_API_KEY;
  const groqKey = process.env.GROQ_API_KEY;

  const count = Math.min(Math.max(options.count || 5, 1), 50);

  const prompt = `Tu es un expert du commerce au Bénin et en Afrique de l'Ouest.
Génère EXACTEMENT ${count} avis clients réalistes et authentiques pour le produit : "${options.productName}".
Description du produit : "${options.productDescription || ''}".

Règles impératives :
1. Noms béninois crédibles parmi : ${BENIN_NAMES.join(', ')}.
2. Villes et quartiers réels : Cotonou (Akpakpa, Cadjehoun, Fidjrossè, Agla, Gbégamey), Porto-Novo, Calavi, Parakou.
3. Mentionner le contexte ouest-africain : appel rapide du service client, livraison par zémidjan/moto, paiement à la livraison en espèces ou MTN MoMo / Moov Money / Wave.
4. Notes : majorité de 5 étoiles avec quelques 4 étoiles constructives.
5. Langue souhaitée : ${options.language || 'FR'} (si MIX, mélange Français et quelques expressions béninoises/fongbe courantes).
6. Réponds STRICTEMENT au format JSON comme un tableau d'objets avec les clés exactes suivantes :
[
  {
    "authorName": "Prénom et Nom",
    "rating": 5,
    "title": "Titre accrocheur",
    "comment": "Commentaire détaillé et authentique"
  }
]`;

  // 1. Essai avec Groq Llama 3.1
  if (groqKey && !groqKey.includes('xxxx')) {
    try {
      const res = await fetch('https://api.groq.com/openai/v1/chat/completions', {
        method: 'POST',
        headers: {
          'Authorization': `Bearer ${groqKey}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          model: 'llama-3.1-70b-versatile',
          messages: [{ role: 'user', content: prompt }],
          temperature: 0.7,
          response_format: { type: 'json_object' },
        }),
      });

      if (res.ok) {
        const data = await res.json();
        const content = data.choices[0]?.message?.content;
        const parsed = JSON.parse(content);
        const list = Array.isArray(parsed) ? parsed : parsed.reviews || Object.values(parsed)[0];
        if (Array.isArray(list)) {
          return list.map((item: any) => ({
            authorName: item.authorName || 'Client MAHUGNON',
            rating: Number(item.rating) || 5,
            title: item.title || 'Très bon produit',
            comment: item.comment || '',
            isVerifiedPurchase: true,
            isAutoGenerated: true,
          }));
        }
      }
    } catch (e) {
      console.warn('Erreur Groq, fallback vers OpenAI ou générateur local', e);
    }
  }

  // 2. Essai avec OpenAI GPT-4o-mini
  if (openAiKey && !openAiKey.includes('xxxx')) {
    try {
      const res = await fetch('https://api.openai.com/v1/chat/completions', {
        method: 'POST',
        headers: {
          'Authorization': `Bearer ${openAiKey}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          model: 'gpt-4o-mini',
          messages: [{ role: 'user', content: prompt }],
          temperature: 0.7,
        }),
      });

      if (res.ok) {
        const data = await res.json();
        const content = data.choices[0]?.message?.content;
        const jsonMatch = content.match(/\[[\s\S]*\]/);
        if (jsonMatch) {
          const list = JSON.parse(jsonMatch[0]);
          return list.map((item: any) => ({
            authorName: item.authorName || 'Client MAHUGNON',
            rating: Number(item.rating) || 5,
            title: item.title || 'Très bon produit',
            comment: item.comment || '',
            isVerifiedPurchase: true,
            isAutoGenerated: true,
          }));
        }
      }
    } catch (e) {
      console.warn('Erreur OpenAI, utilisation du générateur local ultra-réaliste', e);
    }
  }

  // 3. Fallback immédiat et robuste garantissant 100% de disponibilité sans clé
  return generateFallbackReviews(options);
}
