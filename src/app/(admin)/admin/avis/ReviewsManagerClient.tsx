'use client';

import React, { useState } from 'react';
import { Star, CheckCircle, XCircle, Sparkles, Trash2, Check, X } from 'lucide-react';

export const ReviewsManagerClient: React.FC<{ initialReviews: any[] }> = ({ initialReviews }) => {
  const [reviews, setReviews] = useState<any[]>(initialReviews);

  const handleUpdateStatus = (id: string, newStatus: string) => {
    setReviews((prev) =>
      prev.map((r) => (r.id === id ? { ...r, status: newStatus } : r))
    );
  };

  const handleDelete = (id: string) => {
    setReviews((prev) => prev.filter((r) => r.id !== id));
  };

  return (
    <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-100 dark:border-slate-800 shadow-sm overflow-hidden">
      <div className="overflow-x-auto">
        <table className="w-full text-left text-xs">
          <thead className="bg-slate-50 dark:bg-slate-800/60 border-b border-slate-100 dark:border-slate-800 text-slate-500 font-bold uppercase tracking-wider text-[11px]">
            <tr>
              <th className="py-3.5 px-4">Auteur</th>
              <th className="py-3.5 px-4">Article</th>
              <th className="py-3.5 px-4">Note</th>
              <th className="py-3.5 px-4">Commentaire</th>
              <th className="py-3.5 px-4">Origine</th>
              <th className="py-3.5 px-4">Statut</th>
              <th className="py-3.5 px-4 text-right">Actions</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
            {reviews.map((rev) => (
              <tr
                key={rev.id}
                className="hover:bg-slate-50/60 dark:hover:bg-slate-800/40 transition-colors"
              >
                <td className="py-3.5 px-4 font-bold text-slate-900 dark:text-slate-100">
                  {rev.authorName}
                </td>

                <td className="py-3.5 px-4 font-semibold text-blue-600 dark:text-blue-400">
                  {rev.product?.name || 'Produit'}
                </td>

                <td className="py-3.5 px-4">
                  <div className="flex text-amber-400">
                    {[...Array(5)].map((_, i) => (
                      <Star
                        key={i}
                        className={`w-3.5 h-3.5 ${i < rev.rating ? 'fill-current' : 'text-slate-200'}`}
                      />
                    ))}
                  </div>
                </td>

                <td className="py-3.5 px-4 max-w-xs">
                  <p className="font-bold text-slate-800 dark:text-slate-200 truncate">
                    {rev.title}
                  </p>
                  <p className="text-[11px] text-slate-500 line-clamp-2">
                    {rev.comment}
                  </p>
                </td>

                <td className="py-3.5 px-4">
                  {rev.isAutoGenerated ? (
                    <span className="inline-flex items-center gap-1 text-[10px] bg-purple-100 text-purple-700 dark:bg-purple-950 dark:text-purple-300 font-bold px-2 py-0.5 rounded-full">
                      <Sparkles className="w-3 h-3 text-amber-500" />
                      <span>IA Bénin</span>
                    </span>
                  ) : (
                    <span className="text-[10px] bg-slate-100 text-slate-600 dark:bg-slate-800 dark:text-slate-300 font-bold px-2 py-0.5 rounded-full">
                      Client Réel
                    </span>
                  )}
                </td>

                <td className="py-3.5 px-4">
                  <span
                    className={`inline-block px-2 py-0.5 rounded-full text-[10px] font-black uppercase ${
                      rev.status === 'APPROVED'
                        ? 'bg-emerald-100 text-emerald-800 dark:bg-emerald-950 dark:text-emerald-300'
                        : rev.status === 'REJECTED'
                        ? 'bg-red-100 text-red-800 dark:bg-red-950 dark:text-red-300'
                        : 'bg-amber-100 text-amber-800 dark:bg-amber-950 dark:text-amber-300'
                    }`}
                  >
                    {rev.status === 'APPROVED'
                      ? 'Approuvé'
                      : rev.status === 'REJECTED'
                      ? 'Rejeté'
                      : 'En attente'}
                  </span>
                </td>

                <td className="py-3.5 px-4 text-right">
                  <div className="flex items-center justify-end gap-1.5">
                    {rev.status !== 'APPROVED' && (
                      <button
                        onClick={() => handleUpdateStatus(rev.id, 'APPROVED')}
                        className="p-1.5 rounded-lg bg-emerald-50 text-emerald-600 hover:bg-emerald-600 hover:text-white"
                        title="Approuver"
                      >
                        <Check className="w-3.5 h-3.5" />
                      </button>
                    )}
                    {rev.status !== 'REJECTED' && (
                      <button
                        onClick={() => handleUpdateStatus(rev.id, 'REJECTED')}
                        className="p-1.5 rounded-lg bg-amber-50 text-amber-600 hover:bg-amber-600 hover:text-white"
                        title="Rejeter"
                      >
                        <X className="w-3.5 h-3.5" />
                      </button>
                    )}
                    <button
                      onClick={() => handleDelete(rev.id)}
                      className="p-1.5 rounded-lg bg-red-50 text-red-600 hover:bg-red-600 hover:text-white"
                      title="Supprimer"
                    >
                      <Trash2 className="w-3.5 h-3.5" />
                    </button>
                  </div>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
};
