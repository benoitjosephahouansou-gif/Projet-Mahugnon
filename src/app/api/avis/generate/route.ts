import { NextRequest, NextResponse } from 'next/server';
import { prisma } from '@/lib/prisma';
import { generateAIReviews } from '@/lib/ai-reviews';
import { ReviewStatus } from '@prisma/client';

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const { productId, productName, productDescription, count = 3, language = 'FR' } = body;

    if (!productId) {
      return NextResponse.json({ error: 'Le productId est requis' }, { status: 400 });
    }

    const product = await prisma.product.findUnique({
      where: { id: productId },
      select: { id: true, shopId: true, name: true, description: true },
    });

    if (!product) {
      return NextResponse.json({ error: 'Produit introuvable' }, { status: 404 });
    }

    // Génération des avis via IA (OpenAI / Groq ou générateur culturel béninois)
    const generated = await generateAIReviews({
      productName: productName || product.name,
      productDescription: productDescription || product.description,
      count: Math.min(Number(count) || 3, 20),
      language,
    });

    const savedReviews = [];

    for (const item of generated) {
      const rev = await prisma.review.create({
        data: {
          shopId: product.shopId,
          productId: product.id,
          authorName: item.authorName,
          rating: item.rating,
          title: item.title,
          comment: item.comment,
          isVerifiedPurchase: item.isVerifiedPurchase,
          isAutoGenerated: true,
          status: ReviewStatus.APPROVED,
        },
      });
      savedReviews.push(rev);
    }

    return NextResponse.json({
      success: true,
      count: savedReviews.length,
      reviews: savedReviews,
    });
  } catch (error: any) {
    console.error('Erreur API /api/avis/generate:', error);
    return NextResponse.json(
      { error: error?.message || 'Erreur lors de la génération des avis' },
      { status: 500 }
    );
  }
}
